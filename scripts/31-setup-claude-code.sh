#!/usr/bin/env bash
# =============================================================================
# 31-setup-claude-code.sh — wire Claude Code CLI to GitHub + local Ollama
# =============================================================================
# Option B: Claude Code (cloud subscription) does the heavy reasoning;
# the local Ollama instance is exposed as an MCP "worker" for cheap, private
# work (summarising long files, generating boilerplate, embeddings, etc.).
#
# What this does:
#   1. Verifies edge-ollama is running and a coding model is installed.
#   2. Installs Node.js 20 if missing (nvm for non-root, NodeSource for root).
#   3. Installs the Claude Code CLI (npm) if missing.
#   4. Registers two MCP servers on the user's Claude Code config:
#        - github       (official MCP server, requires GITHUB_TOKEN)
#        - ollama       (local stdio server in this repo)
#
# Login to Claude Code is interactive — run `claude` afterwards and follow
# the prompts (use your existing Anthropic / Claude subscription).
#
# Env (optional):
#   GITHUB_TOKEN          fine-grained PAT with repo scope. If unset, the
#                         GitHub MCP server is skipped — you can re-run later.
#   OLLAMA_DEFAULT_MODEL  override the default Ollama model (default qwen2.5-coder:7b)
#   EDGE_NODE_INSTALL     how to install Node.js when missing:
#                           auto       — nvm if non-root, NodeSource if root (default)
#                           nvm        — user-local, no sudo
#                           nodesource — system-wide via apt, needs sudo
#                           skip       — fail with manual instructions
# =============================================================================

# shellcheck source=lib/common.sh
source "$(dirname "$0")/lib/common.sh"
# shellcheck source=lib/manifest.sh
source "$(dirname "$0")/lib/manifest.sh"
load_env  # so manifest knows about $AI_DATA_ROOT

DEFAULT_MODEL="${OLLAMA_DEFAULT_MODEL:-qwen2.5-coder:7b}"
EMBED_MODEL="${OLLAMA_EMBED_MODEL:-nomic-embed-text}"
MCP_SERVER="$REPO_ROOT/scripts/lib/ollama-mcp-server.py"
NODE_INSTALL_MODE="${EDGE_NODE_INSTALL:-auto}"
NVM_VERSION="v0.40.1"
NODE_LTS_MAJOR="20"
# Set by ensure_node when global npm installs need elevation.
NPM_SUDO=""

section "🤝 Claude Code + Ollama-as-worker (Option B)"

check_docker
ensure_ollama_running

# --- 1. Coding model --------------------------------------------------------
if docker exec edge-ollama ollama list 2>/dev/null | awk 'NR>1 {print $1}' | grep -qx "$DEFAULT_MODEL"; then
  ok "Coding model installed: $DEFAULT_MODEL"
else
  info "Pulling coding model: $DEFAULT_MODEL"
  bash "$REPO_ROOT/scripts/04-pull-model.sh" "$DEFAULT_MODEL"
fi

# --- 2. Node.js + Claude Code CLI -------------------------------------------
install_node_via_nvm() {
  info "Installing Node.js ${NODE_LTS_MAJOR} via nvm (user-local, no sudo)…"
  require_cmd curl
  export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
  if [[ ! -s "$NVM_DIR/nvm.sh" ]]; then
    curl -fsSL "https://raw.githubusercontent.com/nvm-sh/nvm/${NVM_VERSION}/install.sh" | bash
  fi
  # shellcheck disable=SC1091
  . "$NVM_DIR/nvm.sh"
  nvm install "$NODE_LTS_MAJOR" >/dev/null
  nvm use "$NODE_LTS_MAJOR" >/dev/null
  ok "Node.js $(node --version), npm $(npm --version) (via nvm)"
}

# Install a small wrapper so `claude` works in any shell without sourcing nvm.
# /usr/local/bin is on PATH by default on Ubuntu, so the current shell picks
# it up immediately (no need to open a new terminal).
install_claude_wrapper() {
  # Only needed when claude was installed under nvm.
  local node_bin nvm_node_dir node_ver bin_dir
  node_bin="$(command -v node || true)"
  [[ -n "$node_bin" ]] || return 0
  nvm_node_dir="${NVM_DIR:-$HOME/.nvm}/versions/node"
  [[ -d "$nvm_node_dir" ]] || return 0
  case "$node_bin" in
    "$nvm_node_dir"/*) ;;
    *) return 0 ;;
  esac
  node_ver="$(node --version)"
  bin_dir="$nvm_node_dir/$node_ver/bin"
  [[ -x "$bin_dir/claude" ]] || return 0

  local tmp target
  tmp="$(mktemp)"
  cat >"$tmp" <<EOF
#!/usr/bin/env bash
# Auto-generated by scripts/31-setup-claude-code.sh — do not edit.
export PATH="$bin_dir:\$PATH"
exec "$bin_dir/claude" "\$@"
EOF
  chmod u+rwX,g+rwX,o-rwx "$tmp"
  target="$(install_wrapper claude "$tmp")"
  rm -f "$tmp"
  manifest_add_path "$target"
  ok "Installed claude wrapper: $target"
  warn_if_not_on_path "$(dirname "$target")"
}

install_node_via_nodesource() {
  info "Installing Node.js ${NODE_LTS_MAJOR} via NodeSource apt (system-wide)…"
  require_cmd curl
  local setup_url="https://deb.nodesource.com/setup_${NODE_LTS_MAJOR}.x"
  if [[ $EUID -eq 0 ]]; then
    curl -fsSL "$setup_url" | bash -
    apt-get install -y nodejs
    NPM_SUDO=""
  else
    require_cmd sudo
    curl -fsSL "$setup_url" | sudo -E bash -
    sudo apt-get install -y nodejs
    # System-wide prefix needs root for `npm install -g`.
    NPM_SUDO="sudo"
  fi
  ok "Node.js $(node --version), npm $(npm --version) (via NodeSource)"
}

ensure_node() {
  if command -v npm >/dev/null 2>&1; then
    ok "npm already available: $(npm --version)"
    return 0
  fi

  local mode="$NODE_INSTALL_MODE"
  if [[ "$mode" == "auto" ]]; then
    if [[ $EUID -eq 0 ]]; then
      mode="nodesource"
    else
      mode="nvm"
    fi
  fi

  case "$mode" in
    nvm)        install_node_via_nvm ;;
    nodesource) install_node_via_nodesource ;;
    skip)       die "npm not found and EDGE_NODE_INSTALL=skip. Install Node.js 18+: https://nodejs.org/" ;;
    *)          die "Unknown EDGE_NODE_INSTALL='$mode' (expected: auto, nvm, nodesource, skip)" ;;
  esac
}

if command -v claude >/dev/null 2>&1; then
  ok "Claude Code already installed: $(claude --version 2>/dev/null || echo 'unknown')"
else
  ensure_node
  info "Installing Claude Code CLI via npm…"
  if [[ -n "$NPM_SUDO" ]]; then
    $NPM_SUDO npm install -g @anthropic-ai/claude-code
  else
    npm install -g @anthropic-ai/claude-code
  fi
  manifest_add_npm @anthropic-ai/claude-code
fi

# Make `claude` available in every shell without manual nvm sourcing.
install_claude_wrapper

# --- 3. Verify MCP server -----------------------------------------------------
require_cmd python3
if [[ ! -f "$MCP_SERVER" ]]; then
  die "Missing MCP server: $MCP_SERVER"
fi
chmod u+rwX,g+rwX,o-rwx "$MCP_SERVER"

# --- 4. Register MCP servers with Claude Code -------------------------------
# `claude mcp add` writes to the user's Claude Code config.
# `--scope user` makes the server available from any directory.
register_mcp() {
  local name="$1"; shift
  if claude mcp list 2>/dev/null | grep -q "^$name"; then
    info "MCP '$name' already registered — updating"
    claude mcp remove "$name" --scope user >/dev/null 2>&1 || true
  fi
  claude mcp add "$name" --scope user "$@"
  manifest_add_mcp "$name"
  ok "Registered MCP: $name"
}

# Local Ollama worker MCP
OLLAMA_URL="http://localhost:${OLLAMA_PORT:-11434}"
register_mcp ollama \
  --env "OLLAMA_URL=$OLLAMA_URL" \
  --env "OLLAMA_DEFAULT_MODEL=$DEFAULT_MODEL" \
  --env "OLLAMA_EMBED_MODEL=$EMBED_MODEL" \
  -- python3 "$MCP_SERVER"

# GitHub MCP (official, runs via npx)
if [[ -n "${GITHUB_TOKEN:-}" ]]; then
  register_mcp github \
    --env "GITHUB_PERSONAL_ACCESS_TOKEN=$GITHUB_TOKEN" \
    -- npx -y @modelcontextprotocol/server-github
else
  warn "GITHUB_TOKEN not set — skipping GitHub MCP registration."
  warn "Create a fine-grained PAT (repo scope) at https://github.com/settings/tokens"
  warn "Then re-run:  GITHUB_TOKEN=ghp_xxx bash scripts/31-setup-claude-code.sh"
fi

log ""
section "✅ Done"
cat <<EOF
Next steps:

  1. Log in to Claude Code (uses your existing Anthropic subscription):
       claude login

  2. Start a session in this repo:
       cd $REPO_ROOT
       claude

  3. Inside Claude, verify the MCP servers are connected:
       /mcp

You should see 'ollama' (and 'github' if you set GITHUB_TOKEN) listed.
Claude can now offload local-friendly work to Ollama via tool calls like:
  ollama_generate, ollama_summarize, ollama_embed, ollama_list_models.

Full guide: docs/AI-CODING-SETUP.md
EOF
